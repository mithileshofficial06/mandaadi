// Generates src/shared/core/trigTable.ts: integer lookup tables for the deterministic core.
// Run once (npm run gen:trig) and commit the output. The game never calls Math.sin at runtime,
// so every phone and the server get bit-identical results.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const QUARTER = 1024; // a full turn is 4096 angle units
const ONE = 16384; // Q14

const sin = [];
for (let i = 0; i <= QUARTER; i++) sin.push(Math.round(Math.sin((i / QUARTER) * (Math.PI / 2)) * ONE));

// atan(i / 1024) in angle units (4096 per turn), for i = 0..1024 (0..45 degrees).
const atan = [];
for (let i = 0; i <= 1024; i++) atan.push(Math.round((Math.atan(i / 1024) / (2 * Math.PI)) * 4096));

const rows = (arr) => {
  const out = [];
  for (let i = 0; i < arr.length; i += 24) out.push('  ' + arr.slice(i, i + 24).join(', ') + ',');
  return out.join('\n');
};

const src = `// GENERATED by tools/gen-trig.mjs. Do not edit by hand.
// SIN_Q: sin of a quarter turn in 1024 steps, Q14 (16384 = 1.0).
// ATAN_Q: atan(i/1024) for i = 0..1024, in angle units (4096 per turn).

export const SIN_Q: readonly number[] = [
${rows(sin)}
];

export const ATAN_Q: readonly number[] = [
${rows(atan)}
];
`;
writeFileSync(resolve(import.meta.dirname, '../src/shared/core/trigTable.ts'), src);
console.log('wrote trigTable.ts', sin.length, atan.length);
